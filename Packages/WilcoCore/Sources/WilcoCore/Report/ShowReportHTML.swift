extension ChannelTint {
    /// Hex colours for HTML: a darker shade for light pages, a lighter one for dark.
    var hexColors: (light: String, dark: String) {
        switch self {
        case .red: ("C62828", "FF6B6B")
        case .orange: ("D9480F", "FFA94D")
        case .yellow: ("B08800", "FFD43B")
        case .green: ("2B8A3E", "69DB7C")
        case .teal: ("0B7285", "63E6BE")
        case .cyan: ("1971C2", "66D9E8")
        case .blue: ("1C4FD8", "74A8FF")
        case .indigo: ("4338CA", "A5B4FC")
        case .purple: ("7E22CE", "D0A2FF")
        case .pink: ("C2255C", "FAA2C1")
        case .gray: ("475569", "ADB5BD")
        }
    }
}
