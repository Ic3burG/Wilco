import Foundation

/// A self-contained HTML page for a show report, laid out like the report
/// window: open it in any browser, print it or send it to the crew. Works
/// offline, follows the reader's light or dark mode, and escapes everything
/// taken from the session, since it is speech from comms.
public enum ShowReportHTML {
    public static func render(_ report: ShowReport, timeZone: TimeZone = .current) -> String {
        let clock = formatter(timeZone, template: "jmmss")
        let title = escape(report.showName)
        let session = escape(report.sourceName.replacingOccurrences(of: ".jsonl", with: ""))
        let date = escape(formatter(timeZone, template: "EEE d MMM yyyy jmm").string(from: report.sessionStart))
        return """
        <!DOCTYPE html>
        <html lang="en"><head><meta charset="utf-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <title>\(title) — \(date)</title>
        <style>\(css)</style>
        </head><body>
        <div class="bar">
          <div class="where"><b>Post-Show</b><span>\(session)</span></div>
          <nav class="tabs">
            <button class="on" data-tab="run">Run of show</button><button data-tab="log">Chat log</button><button data-tab="channels">Channels</button>
          </nav>
          <input type="search" id="q" placeholder="Search words, or &quot;an exact phrase&quot;" autocomplete="off">
        </div>
        <header>
          <h1>\(title) <span>\(date)</span></h1>
          <div class="stats">
            \(stat(duration(report.duration), "duration"))\(stat(report.totalMessages.formatted(), "messages"))\
        \(stat(report.markers.count.formatted(), "markers"))\(stat(report.channels.count.formatted(), "channels"))
          </div>
        </header>
        <div class="chips" id="channel-chips">\(channelChips(report))</div>
        <section id="run">\(runOfShow(report, clock: clock))</section>
        <section id="log" hidden>\(chatLog(report, clock: clock))</section>
        <section id="channels" hidden>\(channels(report))</section>
        <p class="none" id="none" hidden>Nothing matched. Try fewer words, or quote a phrase.</p>
        <footer>Generated by Wilco from \(escape(report.sourceName))</footer>
        <script>\(script)</script>
        </body></html>
        """
    }

    // MARK: Sections

    private static func stat(_ value: String, _ caption: String) -> String {
        #"<div><b>\#(escape(value))</b><span>\#(caption)</span></div>"#
    }

    private static func chip(_ title: String, count: Int?, tint: ChannelTint, attributes: String, on: Bool) -> String {
        let number = count.map { " <span class=\"n\">\($0.formatted())</span>" } ?? ""
        return #"<button class="chip\#(on ? " on" : "")" style="\#(swatch(tint))" \#(attributes)><i></i>\#(escape(title))\#(number)</button>"#
    }

    private static func channelChips(_ report: ShowReport) -> String {
        chip("All channels", count: nil, tint: .gray, attributes: #"data-ch="all""#, on: true)
            + report.groups.map {
                let ids = $0.channelIDs.map(\.uuidString).joined(separator: ",")
                return chip("📁 " + $0.name, count: nil, tint: .gray, attributes: #"data-group="\#(ids)""#, on: false)
            }.joined()
            + report.channels.filter { $0.messages > 0 }.map {
                chip($0.name, count: $0.messages, tint: $0.tint, attributes: #"data-ch="\#($0.id)""#, on: false)
            }.joined()
    }

    private static func timeCell(_ date: Date, _ elapsed: Double, clock: DateFormatter) -> String {
        #"<td class="time"><b>\#(escape(clock.string(from: date)))</b><span>\#(offset(elapsed))</span></td>"#
    }

    private static func channelCell(_ name: String, _ tint: ChannelTint) -> String {
        #"<td class="who" style="\#(swatch(tint))">\#(escape(name))</td>"#
    }

    private static func runOfShow(_ report: ShowReport, clock: DateFormatter) -> String {
        guard !report.markers.isEmpty else {
            return #"<p class="none">No house light calls, cue calls or show terms were heard on any channel.</p>"#
        }
        let categories = ShowReport.MarkerCategory.allCases.compactMap { category -> String? in
            let count = report.markers.count { $0.category == category }
            guard count > 0 else { return nil }
            return chip(category.title, count: count, tint: category.tint, attributes: #"data-cat="\#(category.rawValue)""#, on: false)
        }.joined()
        let rows = report.markers.map { marker in
            let repeats = marker.repeats > 1 ? #" <span class="rep">×\#(marker.repeats)</span>"# : ""
            return """
            <tr data-ch="\(marker.channelID)" data-cat="\(marker.category.rawValue)">\
            \(timeCell(marker.date, marker.elapsed, clock: clock))\
            <td class="what" style="\(swatch(marker.category.tint))"><i></i><b>\(escape(marker.label))</b>\(repeats)</td>\
            \(channelCell(marker.channelName, marker.tint))\
            <td class="said">\(marked(marker.text, phrase: marker.matched))</td></tr>
            """
        }.joined(separator: "\n")
        let everything = chip("Everything", count: report.markers.count, tint: .gray, attributes: #"data-cat="all""#, on: true)
        return #"<div class="chips cats">\#(everything)\#(categories)</div><table class="rows">\#(rows)</table>"#
    }

    private static func chatLog(_ report: ShowReport, clock: DateFormatter) -> String {
        let rows = report.messages.map { message in
            let unsure = (message.confidence ?? 1) < ShowReport.unclearBelow
            let title = message.confidence.map { #" title="\#(Int(($0 * 100).rounded()))% confidence""# } ?? ""
            return """
            <tr data-ch="\(message.channelID)">\(timeCell(message.date, message.elapsed, clock: clock))\
            \(channelCell(message.channelName, message.tint))\
            <td class="said\(unsure ? " unsure" : "")"\(title)>\(escape(message.text))</td></tr>
            """
        }.joined(separator: "\n")
        return #"<table class="rows log">\#(rows)</table>"#
    }

    private static func channels(_ report: ShowReport) -> String {
        let busiest = max(report.channels.map(\.messages).max() ?? 1, 1)
        let stats = report.channels.map { channel in
            var details = ["\(channel.words.formatted()) words"]
            if let mean = channel.meanConfidence {
                details.append("\(Int((mean * 100).rounded()))% mean confidence")
                details.append("\(channel.unclear) unclear")
            }
            if let start = channel.busiestStart {
                details.append("busiest \(offset(start))")
                details.append("\(channel.busiestCount) in \(Int(ShowReport.busiestWindow / 60)) min")
            }
            let terms = channel.topTerms.map { #"<span>\#(escape($0.word)) <b>\#($0.count)</b></span>"# }.joined()
            let width = max(1, Double(channel.messages) / Double(busiest) * 100)
            return """
            <div class="ch" data-ch="\(channel.id)" style="\(swatch(channel.tint))">\
            <div class="name"><i></i>\(escape(channel.name))</div>\
            <div class="body"><div class="track"><div style="width:\(String(format: "%.1f", width))%"></div></div>\
            <p>\(details.joined(separator: " · "))</p><div class="terms">\(terms)</div></div>\
            <div class="count"><b>\(channel.messages.formatted())</b><span>\(String(format: "%.1f", channel.share * 100))%</span></div></div>
            """
        }.joined(separator: "\n")
        return """
        <h2>Messages per channel</h2>\(stats)
        <h2>Traffic</h2><p class="note">One column per \(duration(report.bucketSeconds)), shaded by messages in that window.</p>
        \(traffic(report))
        """
    }

    private static func traffic(_ report: ShowReport) -> String {
        let rows = report.channels.map { channel in
            let counts = report.buckets.map { $0.counts[channel.id] ?? 0 }
            let peak = Double(max(counts.max() ?? 0, 1))
            let columns = counts.map { count -> String in
                guard count > 0 else { return "<i></i>" }
                let ratio = Double(count) / peak
                return String(format: #"<i style="height:%.0f%%;opacity:%.2f" title="%d"></i>"#, 30 + 70 * ratio, 0.4 + 0.6 * ratio, count)
            }.joined()
            return #"<div class="heat" data-ch="\#(channel.id)" style="\#(swatch(channel.tint))"><span>\#(escape(channel.name))</span><div class="cols">\#(columns)</div></div>"#
        }.joined(separator: "\n")
        let span = Double(report.buckets.count) * report.bucketSeconds
        let ticks = (0..<6).map { tick in
            String(format: #"<span style="left:%.2f%%">%@</span>"#, Double(tick) / 6 * 100, offset(span * Double(tick) / 6))
        }.joined()
        return #"<div class="traffic">\#(rows)<div class="heat axis"><span></span><div class="ticks">\#(ticks)</div></div></div>"#
    }

    // MARK: Helpers

    /// The text, escaped, with each place the call was heard marked.
    static func marked(_ text: String, phrase: String) -> String {
        var html = ""
        var cursor = text.startIndex
        for range in PhraseLocator.ranges(of: phrase, in: text) where range.lowerBound >= cursor {
            html += escape(String(text[cursor..<range.lowerBound]))
            html += #"<mark class="call">\#(escape(String(text[range])))</mark>"#
            cursor = range.upperBound
        }
        return html + escape(String(text[cursor...]))
    }

    static func escape(_ text: String) -> String {
        text.replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
            .replacingOccurrences(of: "'", with: "&#39;")
    }

    private static func offset(_ seconds: Double) -> String {
        let total = max(0, Int(seconds))
        return String(format: "%d:%02d:%02d", total / 3600, total / 60 % 60, total % 60)
    }

    private static func duration(_ seconds: Double) -> String {
        let minutes = Int(seconds / 60)
        return minutes >= 60 ? "\(minutes / 60) h \(String(format: "%02d", minutes % 60)) min" : "\(minutes) min"
    }

    private static func formatter(_ timeZone: TimeZone, template: String) -> DateFormatter {
        let formatter = DateFormatter()
        formatter.timeZone = timeZone
        formatter.setLocalizedDateFormatFromTemplate(template)
        return formatter
    }

    /// A colour for light and dark pages.
